CREATE TABLE promotions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(32)    NOT NULL UNIQUE,
    type               VARCHAR(32)    NOT NULL,
    discount_kind      VARCHAR(16)    NOT NULL CHECK (discount_kind IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    discount_value     NUMERIC(19, 4) NOT NULL CHECK (discount_value > 0),
    currency           VARCHAR(3)     NOT NULL,
    min_subtotal       NUMERIC(19, 4) NOT NULL DEFAULT 0,
    max_discount       NUMERIC(19, 4),
    usage_limit        INT            NOT NULL DEFAULT 0,
    per_customer_limit INT            NOT NULL DEFAULT 0,
    used_count         INT            NOT NULL DEFAULT 0,
    starts_at          TIMESTAMPTZ,
    ends_at            TIMESTAMPTZ,
    active             BOOLEAN        NOT NULL DEFAULT TRUE,
    description        TEXT,
    version            BIGINT         NOT NULL DEFAULT 0,
    -- Hàng rào cuối cùng chống bán quá lượt, phòng khi code có lỗi.
    CONSTRAINT promotions_usage_chk CHECK (usage_limit = 0 OR used_count <= usage_limit),
    CONSTRAINT promotions_used_chk CHECK (used_count >= 0)
);

CREATE TABLE redemptions (
    order_id     VARCHAR(36)    PRIMARY KEY,
    promotion_id BIGINT         NOT NULL REFERENCES promotions (id),
    customer_id  VARCHAR(64)    NOT NULL,
    discount     NUMERIC(19, 4) NOT NULL,
    currency     VARCHAR(3)     NOT NULL,
    cancelled    BOOLEAN        NOT NULL DEFAULT FALSE,
    redeemed_at  TIMESTAMPTZ    NOT NULL
);

CREATE INDEX redemptions_customer ON redemptions (promotion_id, customer_id) WHERE NOT cancelled;
